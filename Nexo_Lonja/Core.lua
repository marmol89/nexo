        end
    elseif low == Cmd("help") then
        print(P .. Tr("comandos:"))
        print("  |cffffff00/lonja|r - " .. Tr("abrir/cerrar la ventana"))
        print("  |cffffff00/lonja <texto>|r - " .. Tr("abrir buscando ese texto en los precios guardados"))
